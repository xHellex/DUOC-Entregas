-- 4.1 Creación de Vista VW_EMPRESAS_ASESORADAS
-- Lógica: Filtro paramétrico (Año actual - 1) usando la columna 'FIN'
CREATE OR REPLACE VIEW VW_EMPRESAS_ASESORADAS AS
SELECT 
    e.RUT_EMPRESA || '-' || e.DV_EMPRESA AS "RUT EMPRESA",
    e.NOMEMPRESA AS "NOMBRE EMPRESA",
    TRUNC(MONTHS_BETWEEN(SYSDATE, e.FECHA_INICIACION_ACTIVIDADES)/12) AS "AÑOS ANTIGUEDAD",
    TO_CHAR(e.IVA_DECLARADO, '$999G999G999') AS "IVA DECLARADO",
    
    COUNT(*) AS "TOTAL ASESORIAS ANUAL",
    ROUND(COUNT(*) / 12) AS "ASESORIAS PROMEDIO MENSUAL",
    TO_CHAR(ROUND(e.IVA_DECLARADO * (ROUND(COUNT(*) / 12) / 100)), '$999G999G999') AS "DEVOLUCION IVA ESTIMADA",
    
    -- Categorización Cliente
    CASE 
        WHEN ROUND(COUNT(*) / 12) > 5 THEN 'CLIENTE PREMIUM'
        WHEN ROUND(COUNT(*) / 12) BETWEEN 3 AND 5 THEN 'CLIENTE'
        ELSE 'CLIENTE POCO CONCURRIDO'
    END AS "TIPO CLIENTE",
    
    -- Promociones (Case Anidado)
    CASE 
        WHEN ROUND(COUNT(*) / 12) > 5 THEN
            CASE WHEN COUNT(*) >= 7 THEN '1 ASESORÍA GRATIS' ELSE '1 ASESORÍA 40% DE DESCUENTO' END
        WHEN ROUND(COUNT(*) / 12) BETWEEN 3 AND 5 THEN
            CASE WHEN COUNT(*) = 5 THEN '1 ASESORÍA 30% DE DESCUENTO' ELSE '1 ASESORÍA 20% DE DESCUENTO' END
        ELSE 'CAPTAR CLIENTE'
    END AS "PROMOCION SUGERIDA"
FROM 
    L_EMPRESA e
    JOIN L_ASESORIA a ON e.IDEMPRESA = a.IDEMPRESA
WHERE 
    EXTRACT(YEAR FROM a.FIN) = EXTRACT(YEAR FROM SYSDATE) - 1
GROUP BY 
    e.RUT_EMPRESA, e.DV_EMPRESA, e.NOMEMPRESA, e.FECHA_INICIACION_ACTIVIDADES, e.IVA_DECLARADO
ORDER BY 
    "NOMBRE EMPRESA" ASC;

-- 4.2 Otorgar permisos al Consultor
GRANT SELECT ON VW_EMPRESAS_ASESORADAS TO PRY2205_EFT_CON;

