-- 3.1 Creación de Tabla CARTOLA_PROFESIONALES
-- Lógica: Join No-Equitativo para rangos de sueldo y CASE para movilización.
CREATE TABLE CARTOLA_PROFESIONALES AS
SELECT 
    p.RUTPROF AS "RUT PROFESIONAL",
    INITCAP(p.NOMPRO || ' ' || p.APPPRO || ' ' || p.APMPRO) AS "NOMBRE COMPLETO",
    UPPER(pr.NOMPROFESION) AS "PROFESION",
    i.NOMISAPRE AS "ISAPRE",
    p.SUELDO AS "SUELDO BASE",
    
    -- Comisión (BD tiene decimales ej: 0.05)
    NVL(p.COMISION, 0) AS "PORCENTAJE COMISION",
    ROUND(p.SUELDO * NVL(p.COMISION, 0)) AS "VALOR COMISION",
    
    -- Honorarios (Desde tabla RANGOS_SUELDOS)
    rs.HONOR_PCT AS "PORCENTAJE HONORARIOS",
    ROUND(p.SUELDO * (rs.HONOR_PCT / 100)) AS "VALOR HONORARIOS",
    
    -- Bono Movilización según contrato
    CASE 
        WHEN UPPER(tc.NOMTCONTRATO) LIKE '%INDEFINIDO JORNADA COMPLETA%' THEN 150000
        WHEN UPPER(tc.NOMTCONTRATO) LIKE '%INDEFINIDO JORNADA PARCIAL%' THEN 120000
        WHEN UPPER(tc.NOMTCONTRATO) LIKE '%PLAZO FIJO%' THEN 60000
        WHEN UPPER(tc.NOMTCONTRATO) LIKE '%HONORARIOS%' THEN 50000
        ELSE 0
    END AS "BONO MOVILIZACION",
    
    -- Total a Pagar
    ROUND(
        p.SUELDO + 
        (p.SUELDO * NVL(p.COMISION, 0)) + 
        (p.SUELDO * (rs.HONOR_PCT / 100)) + 
        CASE 
            WHEN UPPER(tc.NOMTCONTRATO) LIKE '%INDEFINIDO JORNADA COMPLETA%' THEN 150000
            WHEN UPPER(tc.NOMTCONTRATO) LIKE '%INDEFINIDO JORNADA PARCIAL%' THEN 120000
            WHEN UPPER(tc.NOMTCONTRATO) LIKE '%PLAZO FIJO%' THEN 60000
            WHEN UPPER(tc.NOMTCONTRATO) LIKE '%HONORARIOS%' THEN 50000
            ELSE 0
        END
    ) AS "TOTAL A PAGAR"
FROM 
    PROFESIONAL p
    JOIN PROFESION pr ON p.IDPROFESION = pr.IDPROFESION
    JOIN ISAPRE i ON p.IDISAPRE = i.IDISAPRE
    JOIN TIPO_CONTRATO tc ON p.IDTCONTRATO = tc.IDTCONTRATO
    JOIN RANGOS_SUELDOS rs ON p.SUELDO BETWEEN rs.S_MIN AND rs.S_MAX
ORDER BY 
    "PROFESION" ASC, "SUELDO BASE" DESC, "PORCENTAJE COMISION" ASC, "RUT PROFESIONAL" ASC;

-- 3.2 Otorgar permisos al Consultor
GRANT SELECT ON CARTOLA_PROFESIONALES TO PRY2205_EFT_CON;


/*************************************************************************
  BLOQUE 4: CASO 3 - VISTAS Y OPTIMIZACIÓN
